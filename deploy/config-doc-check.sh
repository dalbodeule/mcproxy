#!/bin/sh
set -eu

root=${1:-.}
files="$root/README.md $root/README.ko.md $root/inc.env"
for file in $files; do
	[ -r "$file" ] || { echo "configuration documentation is not readable: $file" >&2; exit 1; }
done

# Keep operator-facing examples synchronized with runtime and preflight names.
variables='
MCPROXY_HTTP_ADDR
MCPROXY_GATE_BIND
MCPROXY_GATE_ONLINE_MODE
MCPROXY_GATE_PROXY_PROTOCOL
MCPROXY_GATE_PROXY_PROTOCOL_TRUSTED_PROXIES
MCPROXY_GATE_PROXY_PROTOCOL_BACKEND
MCPROXY_GATE_MAX_CONCURRENT_LOGINS_PER_IP
MCPROXY_GATE_FORWARDING_MODE
MCPROXY_GATE_VELOCITY_SECRET
MCPROXY_PING_CACHE_TTL_SEC
MCPROXY_PING_FALLBACK_MOTD
MCPROXY_PING_OFFLINE_MOTD
MCPROXY_PING_FALLBACK_FAVICON
MCPROXY_ADMIN_TOKEN
MCPROXY_ADMIN_ACTOR_SECRET
MCPROXY_ADMIN_THROTTLE
MCPROXY_ADMIN_ALLOWED_ORIGINS
MCPROXY_TRUST_PROXY_HEADERS
MCPROXY_TRUSTED_PROXY_CIDRS
MCPROXY_DB_DRIVER
MCPROXY_SQLITE_PATH
MCPROXY_POSTGRES_DSN
MCPROXY_REQUIRE_POSTGRES_TLS
MCPROXY_REDIS_ADDR
MCPROXY_REDIS_PASSWORD
MCPROXY_REDIS_TLS
MCPROXY_REQUIRE_REDIS_TLS
MCPROXY_REDIS_CHANNEL
MCPROXY_REDIS_FAIL_CLOSED
MCPROXY_GEOIP_PATH
MCPROXY_GEOIP_ASN_PATH
MCPROXY_LOKI_HOST
MCPROXY_LOG_IDENTIFY'

for variable in $variables; do
	for file in $files; do
		grep -Fq "$variable" "$file" || {
			echo "configuration variable is missing from $file: $variable" >&2
			exit 1
		}
	done
done

echo 'Configuration documentation check OK'
